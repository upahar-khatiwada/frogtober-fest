export const DICTIONARIES: Record<Lang, Record<MessageKey, string>> = { en, ne };

export type EnumKind = "procurement_type" | "method" | "buyer_level" | "province" | "language" | "decision" | "status" | "doc_type" | "ingest_status";

/**
 * Look up a label and fill `{name}` placeholders. In Nepali, numeric values are written in
 * Devanagari digits. An unknown key returns the key itself, so a gap is visible, not blank.
 */
export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = DICTIONARIES[lang][key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    if (!(name in vars)) return match;
    const value = vars[name];
    return lang === "ne" && typeof value === "number" ? toDevanagariDigits(value) : String(value);
  });
}

/** Label for an API enum value, e.g. enumLabel("ne", "province", "gandaki") -> "गण्डकी". */
export function enumLabel(lang: Lang, kind: EnumKind, value: string): string {
  const key = `enum.${kind}.${value}` as MessageKey;
  return key in DICTIONARIES[lang] ? DICTIONARIES[lang][key] : value;
}
