"""Export the backend's BS calendar table for the web app (web/lib/nepal/bs-calendar.json).

The UI converts BS <-> AD (expiry date picker, BS/AD toggle) without calling the API, and it must agree
with `nepal.dates` to the day, because the API's DeadlineView and document expiry use that table. JS
calendar packages disagree with `nepali-datetime` from BS 2084 on (future BS years are projections,
NEPAL_CONTEXT section 7), so the web app ships this export instead of a second library.
`tests/test_bs_calendar_export.py` fails if the committed file drifts from the library.

From api/:
  uv run python -m api.scripts.export_bs_calendar
"""

import json
from pathlib import Path
from typing import Any

from nepal.dates import BSDate, bs_to_ad, days_in_bs_month

ROOT = Path(__file__).resolve().parents[2]
OUT_PATH = ROOT / "web" / "lib" / "nepal" / "bs-calendar.json"
MIN_YEAR, MAX_YEAR = 2000, 2099


def build() -> dict[str, Any]:
    years = {
        str(y): {
            "start_ad": bs_to_ad(BSDate(y, 1, 1)).isoformat(),
            "months": [days_in_bs_month(y, m) for m in range(1, 13)],
        }
        for y in range(MIN_YEAR, MAX_YEAR + 1)
    }
    return {
        "source": "nepali-datetime via api/nepal/dates.py (generated by api/scripts/export_bs_calendar.py; do not edit)",
        "min_year": MIN_YEAR,
        "max_year": MAX_YEAR,
        "years": years,
    }


def render() -> str:
    return json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"


def main() -> None:
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT_PATH} (BS {MIN_YEAR}-{MAX_YEAR})")


if __name__ == "__main__":
    main()
